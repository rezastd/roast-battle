// Server sends canonical English foul/crowd strings; map them per language.
export function localizeFoul(foul, lang) {
  const s = STRINGS[lang] || STRINGS.en;
  if (foul.includes("crossed the line")) return s.foulCrossed;
  if (foul.includes("DODGED")) return s.foulDodged;
  if (foul.includes("LOW EFFORT")) return s.foulEffort;
  if (foul.includes("SPLIT CROWD")) return s.foulSplit;
  return foul;
}

export function localizeCrowd(crowd, lang) {
  const s = STRINGS[lang] || STRINGS.en;
  return (
    { cheers: s.crowdCheers, oohs: s.crowdOohs, crickets: s.crowdCrickets, boos: s.crowdBoos }[crowd] ||
    crowd
  );
}
